"""GraphRAG answer generator (LLM).

Role in the pipeline:
- Input: the user's query + a deterministic, structured JSON context from `Organizer`.
- Output: a final natural-language answer (English) generated by an LLM.

This module is intentionally LLM-first. Any strict output formatting should be
handled via prompt instructions, not hard-coded special cases.
"""

import json
import os
from typing import Any, Dict

from haystack import component
from haystack.components.builders import PromptBuilder
from haystack_integrations.components.generators.ollama import OllamaGenerator

from ..config import (
    DEFAULT_OLLAMA_MODEL,
    DEFAULT_OLLAMA_URL,
    DEFAULT_OLLAMA_GENERATOR_NUM_PREDICT,
    DEFAULT_OLLAMA_GENERATOR_TEMPERATURE,
    GRAPH_RAG_DEBUG_ENV,
    OLLAMA_GENERATOR_NUM_PREDICT_ENV,
    OLLAMA_GENERATOR_TEMPERATURE_ENV,
    OLLAMA_GENERATOR_MODEL_ENV,
    OLLAMA_URL_ENV,
)


def _debug_enabled() -> bool:
    return os.getenv(GRAPH_RAG_DEBUG_ENV) == "true"


def _get_env_int(name: str, default: int) -> int:
    value = os.getenv(name)
    if value is None or value.strip() == "":
        return default
    try:
        return int(value)
    except ValueError:
        return default


def _get_env_float(name: str, default: float) -> float:
    value = os.getenv(name)
    if value is None or value.strip() == "":
        return default
    try:
        return float(value)
    except ValueError:
        return default

@component
class Generator:

    """Render an answer based on the JSON analysis context."""

    def __init__(self, model: str | None = None):
        
        # Prefer explicit arg, then generator-specific model from env, else fall back to the config default.
        model_name = model or os.getenv(OLLAMA_GENERATOR_MODEL_ENV) or DEFAULT_OLLAMA_MODEL
        self.model_name = model_name
        ollama_url = os.getenv(OLLAMA_URL_ENV, DEFAULT_OLLAMA_URL)

        num_predict = _get_env_int(
            OLLAMA_GENERATOR_NUM_PREDICT_ENV, DEFAULT_OLLAMA_GENERATOR_NUM_PREDICT
        )
        temperature = _get_env_float(
            OLLAMA_GENERATOR_TEMPERATURE_ENV, DEFAULT_OLLAMA_GENERATOR_TEMPERATURE
        )

        # Prompt template
        self.prompt_builder = PromptBuilder(
                template=(("""
                    SYSTEM
                    You are a deterministic response renderer for IoT measurement data retrieved from a graph.
                    Your only source of information is a JSON object provided in the section "GRAPH CONTEXT (JSON)".
                    You must not use any knowledge outside of this JSON.

                    Language rule
                    Output must be English only.
                    Mandatory JSON structure
                    The GRAPH CONTEXT may contain the following keys:

                    raw.total_records (integer)

                    raw.records (list of raw measurement records)

                    analysis (aggregated statistics, trends, buckets)

                    context (metadata)

                    Output mode selection (strict and exclusive)
                    You must select exactly one output mode.

                    MODE LIST
                    Activate this mode if the user explicitly requests a complete listing of measurements, for example:
                    all measurements, all values, list, raw data, all records, show the data points

                    Rules in MODE LIST

                    Use only raw.records. Never use analysis or context.

                    Output one measurement per line.

                    For each line, output all fields present in the record as plain text in the format
                    key=value separated by spaces.
                    If present, prefer this order:
                    moteid or mote_id, time or ts or epoch or date, temperature, humidity, light, voltage.
                    Omit fields that are not present in the record.
                    Do not invent fields.

                    Limit output to at most 20 lines.
                    Output the first 20 records in the order they appear in raw.records.
                    If raw.total_records is greater than 20, append one final line:
                    ... (additional N measurements omitted)
                    where N equals raw.total_records minus 20.

                    No analysis, no summaries, no trends, no averages, no interpretation.

                    MODE ANSWER
                    Activate this mode in all other cases.

                    Rules in MODE ANSWER

                                        Prefer analysis to answer questions about trends, minimum, maximum, mean, quantiles, or anomalies.

                                        IMPORTANT: Aggregate query results
                                        Sometimes the GRAPH CONTEXT represents an aggregate query (avg/min/max/count) as a single raw record like:
                                        {"value": 1775}
                                        In that case, raw.records[0].value (or any record's numeric "value") IS the aggregate result and MUST be used.
                                        Do NOT confuse this with analysis.stats_global.count:
                                        - analysis.*.*.stats_global.count is the number of data points in the series (often 1 for aggregates),
                                            NOT the answer to "How many measurements".

                    Use raw.records only if the question requires concrete individual values that are not derivable from analysis.

                    If the answer cannot be derived from the JSON, output exactly:
                    No data available.

                    Output format (always enforced)
                    Plain text only.
                    No Markdown.
                    No code blocks.
                    No backticks.
                    No JSON.
                    No introductions.
                    No filler phrases.
                    No follow-up questions.

                    Answer style requirement
                    Never output a bare number by itself.
                    Always produce at least one short English sentence that contains:
                    - the metric name (e.g., Temperature/Humidity/Light/Voltage),
                    - the relevant sensor id when available,
                    - a time or scope when available (e.g., a timestamp, or "Epoch 3"),
                    - and the unit when applicable.

                    Units (fixed mapping)
                    - temperature -> °C
                    - humidity -> %
                    - light -> Lux
                    - voltage -> V

                    Canonical phrasing (match this as closely as possible)
                    For a single measurement value (factual questions):
                    "<MetricLabel> of sensor <sensor_id> at <time>: <value><unit>"
                    (Use the time string exactly as it appears in the JSON. If the question includes a date/time but the JSON only contains a full ISO timestamp, render that full timestamp as-is.)

                    For aggregates (average/min/max/count):
                    "<Aggregate> <MetricLabel> (<Scope>): <value><unit>"
                    Where <Aggregate> is one of: Average / Minimum / Maximum / Number of measurements.
                    <Scope> should be built from the user question (e.g., "Epoch 12", "Sensor 7.0") but the numeric value must come from the JSON.
                    If count is 0, output exactly: No data available.

                    Aggregate value selection priority (strict):
                    1) If raw.records contains a numeric field named "value", use that.
                    2) Else use the most relevant numeric value from analysis (mean/min/max/etc.), but never use stats_global.count as the count answer.

                    For existence questions (e.g., "Is there any light data for sensor 7.0?"):
                    If any matching data exists in the JSON: "<MetricLabel> data is available for sensor <sensor_id>."
                    Otherwise: No data available.

                    Do not mention the background query.
                    Do not mention Cypher.
                    Do not mention pipelines, models, prompts, or retrieval.

                    Consistency rules
                    The sensor name is always the sensor ID (moteid or mote_id).
                    Time fields (time, ts, epoch, date) must be rendered exactly as they appear in the JSON.
                    No normalization, conversion, or interpretation of values.

                    USER QUESTION:
                    {{query}}
                
                    BACKGROUND QUERY (Cypher):
                    {{cypher_query}}

                    GRAPH CONTEXT (retrieved data):
                    {{context}}

                    ANSWER (in English):
                    """
                )),
                required_variables=["query", "cypher_query", "context"]
            )

        # Verbindung zur lokalen Ollama-API
        self.llm = OllamaGenerator(model=model_name,url=ollama_url,
            generation_kwargs={
                "num_predict": num_predict,
                "temperature": temperature,
            },
        )

    @component.output_types(answer=str)
    def run(self, analysis_json: Dict[str, Any], query: str, cypher_query: str = "N/A"):

        """Run the component.

        Args:
            analysis_json: Structured JSON produced by `Organizer`.
            query: Natural-language user question.
            cypher_query: The Cypher query that produced the context (for transparency).

        Returns:
            A dict with key `answer`.
        """

        if _debug_enabled():
            print("\n[generator] input.query:")
            print(query)
            print("[generator] input.cypher_query:")
            print(cypher_query)
            print(f"[generator] model: {self.model_name}")
            print(f"[generator] input.analysis_json keys: {list(analysis_json.keys())}")

        # Convert JSON to string for the prompt
        context_str = json.dumps(analysis_json, indent=2, ensure_ascii=False)

        # Prompt erstellen
        prompt = self.prompt_builder.run(context=context_str, query=query,cypher_query=cypher_query)["prompt"]

        # LLM-Aufruf über Ollama
        response = self.llm.run(prompt=prompt)

        # Antwort extrahieren
        answer = response["replies"][0]

        return {"answer": answer}
